package Day4;

public class Variables
{
    public static void main(String[] args)
    {
        byte byte_variable = 5;

        short short_variable = 10;

        int int_variable = 100;

        long long_variable = 1000L;

        float float_variable = 4.64F;

        double double_variable = 4.64;

        char character_variable = 'A'; // Unicode numbers

        boolean boolean_variable = true;

        System.out.print(boolean_variable);

    }
}
