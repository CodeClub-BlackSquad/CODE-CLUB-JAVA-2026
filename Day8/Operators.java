package Day8;

public class Operators
{
    public static void main(String[] args)
    {
        double num2 = 20.5678;

        int num1 = (int) num2;  // Explicit Type Conversion


        int num3 = 5;

        double num4 = num3; // Implicit Type Conversion

        System.out.println(num4);


        int dividend = 67;
        int divisor = 9;

        System.out.println(dividend % divisor);



    }
}
